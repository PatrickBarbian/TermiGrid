/// Supported UI languages (German is default per specification).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Language {
    #[default]
    De,
    En,
    Fr,
    It,
    Es,
    Pl,
    Nl,
}

impl Language {
    pub const ALL: [Self; 7] = [
        Self::De,
        Self::En,
        Self::Fr,
        Self::It,
        Self::Es,
        Self::Pl,
        Self::Nl,
    ];

    pub fn code(self) -> &'static str {
        match self {
            Self::De => "DE",
            Self::En => "EN",
            Self::Fr => "FR",
            Self::It => "IT",
            Self::Es => "ES",
            Self::Pl => "PL",
            Self::Nl => "NL",
        }
    }

    pub fn display_name(self) -> &'static str {
        match self {
            Self::De => "DE — Deutsch",
            Self::En => "EN — English",
            Self::Fr => "FR — Français",
            Self::It => "IT — Italiano",
            Self::Es => "ES — Español",
            Self::Pl => "PL — Polski",
            Self::Nl => "NL — Nederlands",
        }
    }
}

